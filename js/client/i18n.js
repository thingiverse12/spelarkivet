let current = 'en';

export function setLang(lang) {
  current = STRINGS[lang] ? lang : 'en';
}

export function t(key, vars) {
  const table = STRINGS[current] || STRINGS.en;
  let out = table[key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(new RegExp('\\{' + k + '\\}', 'g'), v);
  return out;
}

/** Localised name for a data-driven item ({name, nameSv}). */
export function tn(item) {
  if (!item) return '';
  return current === 'sv' ? (item.nameSv || item.name) : item.name;
}

export function lang() { return current; }
